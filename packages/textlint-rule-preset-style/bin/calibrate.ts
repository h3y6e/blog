#!/usr/bin/env node
// Regenerates generated/thresholds.json from site/posts. Run via `vp run calibrate-style`.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import type { TxtDocumentNode } from "@textlint/ast-node-types";
import { analyze, type SentenceEndForm } from "../src/morph.ts";
import { allSentences, proseChars, proseSegments, splitSentences } from "../src/prose.ts";
import { band, median, quantile, type Band } from "../src/stats.ts";

const HERE = dirname(fileURLToPath(import.meta.url));
const POSTS = resolve(HERE, "../../../site/posts");
const OUT = resolve(HERE, "../generated/thresholds.json");

const POLITE_THRESHOLD = 0.5;

/** Minimum warn-band width, per metric family. */
const FLOORS = { ratio: 0.08, sentLen: 8, paraLen: 1, vocabulary: 0.05 };

// Reach the markdown parser through textlint. Declaring it as a direct dependency
// makes pnpm link a path without the peer suffix, which does not exist.
const req = createRequire(import.meta.url);
const { parse }: { parse: (markdown: string) => TxtDocumentNode } = req(
  createRequire(req.resolve("textlint")).resolve("@textlint/markdown-to-ast"),
);

const SCRIPTS = ["hiragana", "kanji", "katakana", "latin"] as const;
type Script = (typeof SCRIPTS)[number];

const scriptOf = (ch: string): Script | null => {
  if (/\p{Script=Hiragana}/u.test(ch)) return "hiragana";
  if (/\p{Script=Han}/u.test(ch)) return "kanji";
  if (/[\p{Script=Katakana}ー]/u.test(ch)) return "katakana";
  if (/\p{Script=Latin}/u.test(ch)) return "latin";
  return null;
};

type Article = {
  sentLenMedian: number;
  sentLenMax: number;
  paraLenMedian: number;
  scriptRatio: Record<Script, number>;
  formRatio: Map<SentenceEndForm, number>;
  maxConsecutive: number;
  distinct2: number;
  ttrWindow: number;
};

const measure = async (markdown: string): Promise<Article> => {
  const segments = proseSegments(parse(markdown));
  const sentences = allSentences(segments);
  const chars = proseChars(segments);
  const counts = new Map<Script, number>();
  for (const ch of chars) {
    const script = scriptOf(ch);
    if (script !== null) counts.set(script, (counts.get(script) ?? 0) + 1);
  }
  const record = await analyze(sentences);
  const lengths = sentences.map((sentence) => sentence.text.length);
  const paraLengths = segments
    .map((segment, index) => splitSentences(segment, index).length)
    .filter((count) => count > 0);
  const ratio = (script: Script): number =>
    chars.length === 0 ? 0 : (counts.get(script) ?? 0) / chars.length;
  return {
    sentLenMedian: median(lengths),
    sentLenMax: lengths.length === 0 ? 0 : Math.max(...lengths),
    paraLenMedian: median(paraLengths),
    scriptRatio: {
      hiragana: ratio("hiragana"),
      kanji: ratio("kanji"),
      katakana: ratio("katakana"),
      latin: ratio("latin"),
    },
    formRatio: record.formRatio,
    maxConsecutive: record.maxConsecutive,
    distinct2: record.distinct2,
    ttrWindow: record.ttrWindow,
  };
};

const FORMS = [
  "desu_masu",
  "da_dearu",
  "jotai_verb",
  "jotai_adj",
  "taigen",
  "question",
] as const satisfies readonly SentenceEndForm[];

const formBands = (articles: Article[]): Record<string, Band> =>
  Object.fromEntries(
    FORMS.map((form) => [
      form,
      band(
        articles.map((article) => article.formRatio.get(form) ?? 0),
        FLOORS.ratio,
        true,
      ),
    ]),
  );

const main = async (): Promise<void> => {
  const sources = readdirSync(POSTS)
    .filter((name) => name.endsWith(".md"))
    .toSorted()
    .map((name) => readFileSync(join(POSTS, name), "utf8"));
  const articles = await Promise.all(sources.map((markdown) => measure(markdown)));
  const corpus = articles.filter((article) => Number.isFinite(article.sentLenMedian));
  const polite = corpus.filter(
    (article) => (article.formRatio.get("desu_masu") ?? 0) >= POLITE_THRESHOLD,
  );
  const plain = corpus.filter((article) => !polite.includes(article));
  const runs = corpus.map((article) => article.maxConsecutive);
  const maxConsecutiveWarn = Math.max(3, Math.ceil(quantile(runs, 0.95) - 1e-9));

  const thresholds = {
    $comment: "Generated by `vp run calibrate-style` from site/posts.",
    // Compare against the number of files in site/posts to spot a stale calibration.
    articles: corpus.length,
    sentenceLength: {
      ...band(
        corpus.map((article) => article.sentLenMedian),
        FLOORS.sentLen,
        false,
      ),
      maxWarn: quantile(
        corpus.map((article) => article.sentLenMax),
        0.95,
      ),
      maxHard: Math.max(...corpus.map((article) => article.sentLenMax)),
    },
    paragraphLength: {
      ...band(
        corpus.map((article) => article.paraLenMedian),
        FLOORS.paraLen,
        false,
      ),
    },
    scriptRatio: {
      ranges: Object.fromEntries(
        SCRIPTS.map((script) => [
          script,
          band(
            corpus.map((article) => article.scriptRatio[script]),
            FLOORS.ratio,
            true,
          ),
        ]),
      ),
    },
    sentenceEnd: {
      // Recorded because the bands below are split on it.
      politeThreshold: POLITE_THRESHOLD,
      maxConsecutiveWarn,
      maxConsecutiveHard: Math.max(maxConsecutiveWarn + 2, Math.max(...runs)),
      // Endings are bimodal across registers, so a single band would flag both modes.
      register: {
        plain: { nArticles: plain.length, forms: formBands(plain) },
        polite: { nArticles: polite.length, forms: formBands(polite) },
      },
    },
    vocabulary: {
      distinct2: band(
        corpus.map((article) => article.distinct2),
        FLOORS.vocabulary,
        true,
      ),
      ttrWindow: band(
        corpus.map((article) => article.ttrWindow),
        FLOORS.vocabulary,
        true,
      ),
    },
  };
  writeFileSync(OUT, `${JSON.stringify(thresholds, null, 2)}\n`);
  process.stderr.write(
    `thresholds: ${corpus.length} articles (plain ${plain.length} / polite ${polite.length})\n`,
  );
};

// Top-level await is not Baseline, so keep the entry point promise-based.
main().catch((error: unknown) => {
  process.exitCode = 1;
  console.error(error);
});
